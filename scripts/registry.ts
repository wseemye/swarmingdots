import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Builds the copy-in version of the text swarm: the modules in src/text-swarm
// that make up <DotSwarmText>, joined into one self-contained .tsx file, plus a
// shadcn registry item wrapping it, so
//
//   npx shadcn@latest add https://swarmingdots.vercel.app/r/dot-swarm-text.json
//
// drops that one file into a project. The site renders the same modules, so
// what people install is exactly what the page shows.

const SRC = join(process.cwd(), 'src', 'text-swarm');
const OUT = join(process.cwd(), 'public', 'r');
const NAME = 'dot-swarm-text';
const SITE = 'https://swarmingdots.vercel.app';

// Dependency order: each module only uses what comes before it.
const MODULES = ['anchors.ts', 'words.ts', 'ease.ts', 'rasterize.ts', 'wave.ts', 'Word.tsx', 'DotSwarmText.tsx'];
const MAIN = 'DotSwarmText.tsx';
// Exports from the helper modules that the installed file should still offer.
const PUBLIC = new Set(['Anchor']);

const HEADER = `/**
 * DotSwarmText: text in Geist Pixel Circle that arrives as a swarm of dots.
 * ${SITE}
 *
 *   <DotSwarmText text="hello world" fontSize={40} anchor="top-left" stagger />
 *
 * Each word starts as a block of its own dots, the dots cross to their places in
 * the letters, and the real, selectable text fades in over them. Remount it
 * (change its key) to play it again. Needs React 18 or later; nothing else.
 *
 * Code: MIT License. Font: Geist Pixel by Vercel, SIL Open Font License 1.1,
 * loaded from jsDelivr unless the page already has a Geist Pixel Circle
 * @font-face (pass fontUrl to host it yourself).
 *
 * Generated by scripts/registry.ts from the swarmingdots source; edit freely.
 */`;

const reactNames = new Set<string>();
const parts: string[] = [];

for (const file of MODULES) {
  let src = readFileSync(join(SRC, file), 'utf8');

  src = src.replace(/^'use client';\n+/m, '');
  src = src.replace(/^import \{([^}]*)\} from 'react';\n/m, (_, names: string) => {
    for (const n of names.split(',')) if (n.trim()) reactNames.add(n.trim());
    return '';
  });
  // Everything else it imports is one of the modules joined here.
  src = src.replace(/^import [^;]+ from '\.\/[^']+';\n/gm, '');

  if (file !== MAIN) {
    src = src.replace(/^export default function /gm, 'function ');
    src = src.replace(/^export (const|function|type|async function) (\w+)/gm, (whole, kind: string, name: string) =>
      PUBLIC.has(name) ? whole : `${kind} ${name}`,
    );
  }

  parts.push(`// ── ${file} ${'─'.repeat(Math.max(4, 72 - file.length))}\n\n${src.trim()}\n`);
}

const leftover = parts.join('\n').match(/^import .*$/gm);
if (leftover) throw new Error(`unresolved imports in the bundle:\n${leftover.join('\n')}`);

const values = [...reactNames].filter((n) => !n.startsWith('type ')).sort();
const types = [...reactNames].filter((n) => n.startsWith('type ')).sort();
const reactImport = `import { ${[...values, ...types].join(', ')} } from 'react';`;

const tsx = `'use client';\n\n${HEADER}\n\n${reactImport}\n\n${parts.join('\n')}`;

const item = {
  $schema: 'https://ui.shadcn.com/schema/registry-item.json',
  name: NAME,
  type: 'registry:component',
  title: 'Dot Swarm Text',
  description:
    'Text in Geist Pixel Circle that arrives as a swarm of dots, filling in from a chosen point, with an optional 100ms stagger between words.',
  dependencies: [],
  files: [{ path: `registry/default/${NAME}.tsx`, type: 'registry:component', content: tsx }],
};

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, `${NAME}.tsx`), tsx);
writeFileSync(join(OUT, `${NAME}.json`), `${JSON.stringify(item, null, 2)}\n`);
process.stdout.write(`registry: public/r/${NAME}.json and public/r/${NAME}.tsx (${tsx.split('\n').length} lines)\n`);
