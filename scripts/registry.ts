import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Builds the copy-in version of the text swarm: the modules in src/text-swarm
// that make up <DotSwarmText>, joined into one self-contained .tsx file, plus a
// shadcn registry item wrapping it, so
//
//   npx shadcn@latest add https://dots.wseem.com/r/dot-swarm-text.json
//
// drops that one file into a project. The site renders the same modules, so
// what people install is exactly what the page shows.

const SRC = join(process.cwd(), 'src', 'text-swarm');
const OUT = join(process.cwd(), 'public', 'r');
const NAME = 'dot-swarm-text';
const SITE = 'https://dots.wseem.com';

// Dependency order: each module only uses what comes before it.
const MODULES = ['anchors.ts', 'variants.ts', 'words.ts', 'ease.ts', 'rasterize.ts', 'wave.ts', 'trace.ts', 'gl.ts', 'Word.tsx', 'DotSwarmText.tsx'];
const MAIN = 'DotSwarmText.tsx';
// Exports from the helper modules that the installed file should still offer.
const PUBLIC = new Set(['Anchor', 'Variant', 'Pairing', 'SwarmBy']);

const HEADER = `/**
 * DotSwarmText: text in Geist Pixel that arrives as a swarm of dots.
 * ${SITE}
 *
 *   <DotSwarmText text="hello world" fontSize={40} variant="grid" anchor="top-left" swarmBy="word" />
 *
 * Each word starts as a block of its own dots, the dots cross to their places in
 * the letters, and the real, selectable text takes their place. Remount it
 * (change its key) to play it again. Needs React 18 or later; nothing else.
 *
 * Code: MIT License. Font: Geist Pixel by Vercel, SIL Open Font License 1.1,
 * loaded from jsDelivr unless the page already has an @font-face for the chosen
 * variant ("Geist Pixel Circle", "Geist Pixel Grid", ...; pass fontUrl to host it
 * yourself).
 *
 * Generated by scripts/registry.ts from the swarmingdots source; edit freely.
 */`;

const reactNames = new Set<string>();
const parts: string[] = [];

for (const file of MODULES) {
  let src = readFileSync(join(SRC, file), 'utf8').replace(/\r\n/g, '\n');

  src = src.replace(/^'use client';\n+/m, '');
  src = src.replace(/^import \{([^}]*)\} from 'react';\n/m, (_, names: string) => {
    for (const n of names.split(',')) if (n.trim()) reactNames.add(n.trim());
    return '';
  });
  // Everything else it imports is one of the modules joined here.
  src = src.replace(/^import [^;]+ from '\.\/[^']+';\n/gm, '');

  if (file !== MAIN) {
    src = src.replace(/^export default function /gm, 'function ');
    src = src.replace(/^export (const|function|type|async function) (\w+)/gm, (whole, kind: string, name: string) =>
      PUBLIC.has(name) ? whole : `${kind} ${name}`,
    );
  }

  parts.push(`// ── ${file} ${'─'.repeat(Math.max(4, 72 - file.length))}\n\n${src.trim()}\n`);
}

// Only the editor's typeface picker uses this label; in the copy-in file it would be an unused local.
const unused = /^const variantLabel = .*\n/m;
for (let i = 0; i < parts.length; i++) parts[i] = parts[i].replace(unused, '');

const leftover = parts.join('\n').match(/^import .*$/gm);
if (leftover) throw new Error(`unresolved imports in the bundle:\n${leftover.join('\n')}`);

const values = [...reactNames].filter((n) => !n.startsWith('type ')).sort();
const types = [...reactNames].filter((n) => n.startsWith('type ')).sort();
const reactImport = `import { ${[...values, ...types].join(', ')} } from 'react';`;

const tsx = `'use client';\n\n${HEADER}\n\n${reactImport}\n\n${parts.join('\n')}`;

const item = {
  $schema: 'https://ui.shadcn.com/schema/registry-item.json',
  name: NAME,
  type: 'registry:component',
  title: 'Dot Swarm Text',
  description:
    'Text in Geist Pixel (Circle, Grid, Line or Square) that arrives as a swarm of dots, filling in from a chosen point, optionally letter by letter, word by word, line by line or paragraph by paragraph.',
  dependencies: [],
  files: [{ path: `registry/default/${NAME}.tsx`, type: 'registry:component', content: tsx }],
};

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, `${NAME}.tsx`), tsx);
writeFileSync(join(OUT, `${NAME}.json`), `${JSON.stringify(item, null, 2)}\n`);

// The same file as a page an AI assistant (or a person) can read: what to do with it, how to use
// it, and then the code. The site's "Copy for AI" button points assistants here.
const fence = '`'.repeat(3);
const md = `# DotSwarmText

Text in Geist Pixel that arrives as a swarm of dots. One React component in one file, from ${SITE}.

## Instructions for an AI assistant

1. Save the code below, exactly as it is, as \`dot-swarm-text.tsx\` in this project's components folder
   (for example \`components/\` or \`src/components/\`).
2. Do not run shadcn or install anything: the file needs only React 18 or later.
3. Do not change the project's theme, colours, CSS or fonts.
4. It is a default export and a client component (it starts with \`'use client'\`):
   \`import DotSwarmText from '@/components/dot-swarm-text'\`, with the project's own import alias or a
   relative path.
5. Use it where the user says, with the props they gave. If they gave none, ask for the text.

## Props

| prop            | default     | what it does                                                         |
| --------------- | ----------- | -------------------------------------------------------------------- |
| \`text\`          |             | the text; newlines start a new line                                  |
| \`fontSize\`      | \`26\`        | px; one dot is 0.038 of it                                           |
| \`color\`         | inherited   | dot and text colour: a hex value, or any CSS colour including var(--x) |
| \`variant\`       | \`'circle'\`  | Geist Pixel face: circle, grid, line or square                       |
| \`letterSpacing\` | \`0\`         | extra space after each letter, in dots                               |
| \`lineSpacing\`   | \`6\`         | gap between lines, in dots                                           |
| \`anchor\`        | \`'center'\`  | where each word fills in from (top-left, top, top-right, left, center, ...) |
| \`pairing\`       | \`'scatter'\` | how dots find their places: scatter (random) or trace (pen path)     |
| \`swarmBy\`       | \`'word'\`     | what the swarm is built from: letter makes each letter its own small brick, side by side with no gaps; word, line (as it settles on screen) and paragraph (a line started with Enter) keep a brick per word. With stagger, it is also what takes a turn |
| \`stagger\`       | \`false\`     | start those turns one after another, nearest the anchor first, instead of all together |
| \`staggerMs\`    | \`100\`       | only with stagger: ms between one turn starting and the next, in real time whatever the speed; ignored when stagger is off |
| \`speed\`         | \`0.75\`      | how fast it plays: 1 is about a second a word, 0.5 takes twice as long, 2 half as long |
| \`align\`         | \`'start'\`   | where the block sits in its width                                    |
| \`as\`            | \`'p'\`       | the element that holds the text                                      |
| \`className\`     |             | class for the wrapper                                                |
| \`fontUrl\`       | jsDelivr    | where to load the variant's font if the page has no @font-face       |

Example: \`<DotSwarmText text="hello world" fontSize={40} variant="grid" anchor="top-left" swarmBy="word" />\`

Change its \`key\` to play it again. If the font cannot load, the text shows plainly instead of swarming.
The code is MIT licensed; the font is Geist Pixel by Vercel, SIL Open Font License 1.1.

## dot-swarm-text.tsx

${fence}tsx
${tsx.trimEnd()}
${fence}
`;
writeFileSync(join(OUT, `${NAME}.md`), md);
process.stdout.write(`registry: public/r/${NAME}.json, .tsx and .md (${tsx.split('\n').length} lines)\n`);
